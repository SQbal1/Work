// Graceful degradation: when the database isn't reachable (or isn't configured
// yet), turn the submission into a pre-filled WhatsApp message so no lead is lost.
function showWhatsAppFallback(statusNode, summaryText) {
  if (!statusNode) return;
  const dictionary = currentDictionary();
  statusNode.dataset.state = "error";
  statusNode.dataset.messageKey = "form.fallback";
  statusNode.textContent = `${dictionary["form.fallback"]} `;
  const link = document.createElement("a");
  link.className = "wa-custom";
  link.href = `https://wa.me/${WHATSAPP_NUMBER}?text=${encodeURIComponent(summaryText)}`;
  link.target = "_blank";
  link.rel = "noopener noreferrer";
  link.textContent = dictionary["form.fallbackCta"];
  statusNode.appendChild(link);
}

function readDraft(key) {
  try {
    const draft = localStorage.getItem(key);
    return draft ? JSON.parse(draft) : null;
  } catch {
    return null;
  }
}

function saveFormDraft(form, key) {
  try {
    const draft = {};
    new FormData(form).forEach((value, name) => {
      const field = form.elements[name];
      if (field?.dataset?.spamCheck === "true") return;
      draft[name] = value;
    });
    localStorage.setItem(key, JSON.stringify(draft));
  } catch {
    // Draft saving is local-only and best-effort when storage is unavailable.
  }
}

function restoreFormDraft(form, key) {
  const draft = readDraft(key);
  if (!draft) return;

  Object.entries(draft).forEach(([name, value]) => {
    const field = form.elements[name];
    if (!field || (typeof RadioNodeList !== "undefined" && field instanceof RadioNodeList)) return;
    field.value = value;
  });
}

function clearFormDraft(key) {
  try {
    localStorage.removeItem(key);
  } catch {
    // Ignore storage cleanup failures.
  }
}

if (quoteForm) {
  const quoteDraftKey = "rideXQuoteDraft";
  const quoteReadyAt = performance.now() + MINIMUM_FORM_TIME_MS;
  const fields = Array.from(quoteForm.querySelectorAll("input, select, textarea"));
  const quoteSubmitButton = quoteForm.querySelector(".submit-button");
  restoreFormDraft(quoteForm, quoteDraftKey);

  fields.forEach((field) => {
    field.addEventListener("input", () => {
      saveFormDraft(quoteForm, quoteDraftKey);
      setFieldValidity(field);
      if (formStatus?.dataset.state === "error") {
        formStatus.textContent = "";
        formStatus.dataset.state = "";
        formStatus.dataset.messageKey = "";
      }
    });
    field.addEventListener("change", () => saveFormDraft(quoteForm, quoteDraftKey));
    field.addEventListener("blur", () => setFieldValidity(field));
  });

  quoteForm.addEventListener("submit", async (event) => {
    event.preventDefault();
    saveFormDraft(quoteForm, quoteDraftKey);
    fields.forEach(setFieldValidity);

    if (!quoteForm.checkValidity()) {
      setFormStatus("error", "quotePage.form.error");
      quoteForm.querySelector("[aria-invalid='true']")?.focus();
      return;
    }

    if (isSpamSubmission(quoteForm, quoteReadyAt)) {
      setFormStatus("error", "quotePage.form.submitError");
      return;
    }

    const payload = buildQuotePayload(quoteForm);

    if (!isSupabaseConfigured()) {
      showWhatsAppFallback(formStatus, composeQuoteSummary(payload));
      return;
    }

    setSubmitLoading(quoteSubmitButton, true, "quotePage.form.loading");
    setFormStatus("loading", "quotePage.form.loading");

    try {
      await insertSupabaseRow("quote_requests", payload);
      clearFormDraft(quoteDraftKey);
      quoteForm.reset();
      fields.forEach((field) => field.setAttribute("aria-invalid", "false"));
      setFormStatus("success", "quotePage.form.success");
    } catch (error) {
      console.error("Ride X quote request failed", error);
      showWhatsAppFallback(formStatus, composeQuoteSummary(payload));
    } finally {
      setSubmitLoading(quoteSubmitButton, false);
    }
  });
}

