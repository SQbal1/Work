function cleanText(value) {
  const text = String(value || "").trim();
  return text || null;
}

function cleanInteger(value) {
  const number = parseInt(value, 10);
  return Number.isFinite(number) ? number : null;
}

function isSupabaseConfigured() {
  const url = cleanText(supabaseConfig.url);
  const anonKey = cleanText(supabaseConfig.anonKey);
  return Boolean(
    url &&
      anonKey &&
      url !== "SUPABASE_URL" &&
      anonKey !== "SUPABASE_ANON_KEY" &&
      /^https:\/\/.+\.supabase\.co\/?$/.test(url)
  );
}

async function insertSupabaseRow(tableName, payload) {
  if (!isSupabaseConfigured()) {
    throw new Error("Supabase is not configured.");
  }

  const baseUrl = supabaseConfig.url.replace(/\/$/, "");
  const response = await fetch(`${baseUrl}/rest/v1/${tableName}`, {
    method: "POST",
    headers: {
      apikey: supabaseConfig.anonKey,
      Authorization: `Bearer ${supabaseConfig.anonKey}`,
      "Content-Type": "application/json",
      Prefer: "returning=minimal"
    },
    body: JSON.stringify(payload)
  });

  if (!response.ok) {
    const detail = await response.text();
    throw new Error(detail || `Supabase insert failed with status ${response.status}.`);
  }
}

function isSpamSubmission(form, readyAt) {
  const honeypotValue = cleanText(form.querySelector("[data-spam-check='true']")?.value);
  return Boolean(honeypotValue) || performance.now() < readyAt;
}

function setSubmitLoading(button, loading, loadingKey) {
  if (!button) return;
  button.disabled = loading;
  if (loading) {
    button.dataset.loadingKey = loadingKey;
    button.textContent = currentDictionary()[loadingKey] || button.textContent;
    return;
  }
  delete button.dataset.loadingKey;
  button.textContent = currentDictionary()[button.dataset.i18n] || button.textContent;
}

