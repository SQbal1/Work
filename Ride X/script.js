function localizeNumerals(value, language) {
  if (language !== "ar") return value;
  const arabicIndicDigits = ["٠", "١", "٢", "٣", "٤", "٥", "٦", "٧", "٨", "٩"];
  return value.replace(/\d/g, (digit) => arabicIndicDigits[Number(digit)]);
}

function updateLocalizedNumbers(language) {
  document.querySelectorAll(".card-index").forEach((node) => {
    if (!node.dataset.indexValue) {
      node.dataset.indexValue = node.textContent.trim();
    }
    node.textContent = localizeNumerals(node.dataset.indexValue, language);
  });
}

function setMobileMenu(open) {
  if (!siteHeader || !mobileMenuToggle) return;
  const dictionary = currentDictionary();
  siteHeader.classList.toggle("menu-open", open);
  document.body.classList.toggle("nav-open", open);
  mobileMenuToggle.setAttribute("aria-expanded", String(open));
  mobileMenuToggle.setAttribute("aria-label", dictionary[open ? "nav.closeMenu" : "nav.openMenu"]);
}

function applyLanguage(language) {
  const safeLanguage = language === "ar" ? "ar" : "en";
  const dictionary = translations[safeLanguage];
  document.documentElement.lang = safeLanguage;
  document.documentElement.dir = safeLanguage === "ar" ? "rtl" : "ltr";
  document.documentElement.classList.remove("lang-en", "lang-ar", "language-pending");
  document.documentElement.classList.add(`lang-${safeLanguage}`);
  document.body.dir = document.documentElement.dir;

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (dictionary[key]) {
      node.textContent = dictionary[key];
    }
  });

  updateLocalizedNumbers(safeLanguage);

  document.querySelectorAll(".form-status").forEach((liveStatus) => {
    // The WhatsApp fallback message embeds a link, so leave it untouched on language switch.
    if (liveStatus.dataset.messageKey && liveStatus.dataset.messageKey !== "form.fallback") {
      liveStatus.textContent = dictionary[liveStatus.dataset.messageKey] || "";
    }
  });

  document.querySelectorAll("[data-loading-key][disabled]").forEach((node) => {
    node.textContent = dictionary[node.dataset.loadingKey] || node.textContent;
  });

  if (languageToggle) {
    languageToggle.setAttribute(
      "aria-label",
      safeLanguage === "ar" ? "Switch to English" : "Switch to Arabic"
    );
  }
  if (mobileMenuToggle) {
    const isOpen = mobileMenuToggle.getAttribute("aria-expanded") === "true";
    mobileMenuToggle.setAttribute("aria-label", dictionary[isOpen ? "nav.closeMenu" : "nav.openMenu"]);
  }
  try {
    localStorage.setItem("rideXLanguage", safeLanguage);
  } catch {
    // Language persistence is best-effort when storage is unavailable.
  }
  updateWhatsAppLinks();
}

